// 只列出一之宮（旅人日記、巡拜印等用）
function ichiNames(prov) {
    const s = getSites(prov).shrines;
    const ichi = s.filter(x => (x.r || '').includes('一之宮'));
    return (ichi.length ? ichi : s.slice(0, 1)).map(x => x.short).join('・');
}
function siteNames(prov, type) {
    const s = getSites(prov);
    if (type === 'shrine') {
        const extra = s.shrines.length - s.shrines.filter(x => (x.r || '').includes('一之宮')).length;
        return ichiNames(prov) + (extra > 0 ? `＋名社${extra}座` : '');
    }
    return (type === 'shrine' ? s.shrines : s.castles).map(x => x.short).join('・');
}
function getSites(prov) {
    if (prov._sites) return prov._sites;
    const split = SITE_SPLITS[prov.id] || {};
    const shrines = (split.s || [{
        n: prov.ichinomiya.name, d: prov.ichinomiya.deity, v: prov.ichinomiya.virtue,
        a: prov.ichinomiya.address, t: prov.ichinomiya.desc, m: SHRINE_SPECS[prov.id]
    }]).slice();
    const castles = split.c || [{
        n: prov.castle.name, b: prov.castle.badge, y: prov.castle.type, l: prov.castle.lord,
        t: prov.castle.desc, m: CASTLE_SPECS[prov.id]
    }];
    (EXTRA_SHRINES[prov.id] || []).forEach(s => shrines.push(Object.assign({}, s)));
    const short = n => n.replace(/（.*?）/g, '').replace(/\s*\(.*?\)/g, '').trim();
    shrines.forEach(s => { s.short = short(s.n); s.r = s.r || '一之宮'; });
    castles.forEach(c => {
        c.short = short(c.n);
        if (c.m && c.m.k === 'T' && TENSHU_SHAPES[c.short]) c.m = Object.assign({}, c.m, TENSHU_SHAPES[c.short]);
    });
    prov._sites = { shrines, castles };
    return prov._sites;
}
